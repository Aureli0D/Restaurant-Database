```sql
CREATE TABLE KLIENTI (
    KLIENT_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    EMR_MBI VARCHAR(30) NOT NULL,
    TEL VARCHAR(10),
    EMAIL VARCHAR(50)
);

CREATE TABLE STAFI (
    STAF_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    EMR_MBI VARCHAR(30) NOT NULL,
    ROLI VARCHAR(20) NOT NULL,
    TEL VARCHAR(10) NOT NULL,
    PAGA DECIMAL(10,2) NOT NULL
);

CREATE TABLE TAVOLINA_RESTORANT (
    TAVOLIN_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    TAVOLIN_NR INT NOT NULL,
    KAPACITETI INT NOT NULL,
    STATUSI VARCHAR(20) DEFAULT 'Gati'
);

CREATE TABLE KATEGORIA_MENU (
    KATEGORI_ID VARCHAR(10) PRIMARY KEY,
    EMER_KAT VARCHAR(50) NOT NULL
);

CREATE TABLE PRODUKTE_MENU (
    PRODUKT_ID VARCHAR(10) PRIMARY KEY NOT NULL,
    KATEGORI_ID VARCHAR(10) NOT NULL,
    PRODUKT_EMR VARCHAR(30) NOT NULL,
    CMIMI DECIMAL(10,2) NOT NULL,

    FOREIGN KEY (KATEGORI_ID)
        REFERENCES KATEGORIA_MENU(KATEGORI_ID)
        ON UPDATE CASCADE
);

CREATE TABLE POROSI (
    POROSI_ID INT PRIMARY KEY NOT NULL,
    KLIENT_ID VARCHAR(10) NOT NULL,
    STAF_ID VARCHAR(10) NOT NULL,
    TAVOLIN_ID VARCHAR(10) NOT NULL,
    POROSI_DAT DATETIME DEFAULT CURRENT_TIMESTAMP,
    STATUSI VARCHAR(30) DEFAULT 'Ne Pritje',

    FOREIGN KEY (KLIENT_ID)
        REFERENCES KLIENTI(KLIENT_ID)
        ON UPDATE CASCADE,

    FOREIGN KEY (STAF_ID)
        REFERENCES STAFI(STAF_ID)
        ON UPDATE CASCADE,

    FOREIGN KEY (TAVOLIN_ID)
        REFERENCES TAVOLINA_RESTORANT(TAVOLIN_ID)
        ON UPDATE CASCADE
);

CREATE TABLE FATURA (
    FATURA_ID INT PRIMARY KEY NOT NULL,
    POROSI_ID INT NOT NULL,
    PRODUKT_ID VARCHAR(10) NOT NULL,
    SASIA INT NOT NULL,
    CMIMI DECIMAL(10,2) NOT NULL,

    FOREIGN KEY (POROSI_ID)
        REFERENCES POROSI(POROSI_ID)
        ON UPDATE CASCADE,

    FOREIGN KEY (PRODUKT_ID)
        REFERENCES PRODUKTE_MENU(PRODUKT_ID)
        ON UPDATE CASCADE
);

CREATE TABLE PAGESA (
    PAGESA_ID VARCHAR(5) PRIMARY KEY NOT NULL,
    POROSI_ID INT NOT NULL,
    SHUMA DECIMAL(10,2) NOT NULL,
    METODA VARCHAR(10) NOT NULL,
    DATA_PAGESES DATETIME DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (POROSI_ID)
        REFERENCES POROSI(POROSI_ID)
        ON UPDATE CASCADE
);

CREATE TABLE REZERVIM (
    REZERVIM_ID VARCHAR(5) PRIMARY KEY NOT NULL,
    KLIENT_ID VARCHAR(10) NOT NULL,
    TAVOLIN_ID VARCHAR(10) NOT NULL,
    ORAR_REZERVIMI DATETIME NOT NULL,

    FOREIGN KEY (KLIENT_ID)
        REFERENCES KLIENTI(KLIENT_ID)
        ON UPDATE CASCADE,

    FOREIGN KEY (TAVOLIN_ID)
        REFERENCES TAVOLINA_RESTORANT(TAVOLIN_ID)
        ON UPDATE CASCADE
);
```
